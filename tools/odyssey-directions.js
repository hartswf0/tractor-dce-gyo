#!/usr/bin/env node
/* tools/odyssey-directions.js — the cineosis sign score's DIRECTIONS, carried into the game as a script.

   Reads odyssey/cineosis/score.json (per scene: the primary and secondary signs and the 'direction' block the scorer wrote:
   shot_bias, hold_min_s, move, empty_frame, sound_forward, cut_rhythm, insert_object, subject, book_tempo, tempo_conflict)
   and writes play/odyssey-game/directions.js: `OG.DIR[sceneId] = {d: direction, p: primary symbol, s: [secondary symbols]}`.
   The game layer loads it before cinema.js (tools/odyssey-game.js adds the <script>; tools/odyssey-mobile.js inlines it, so
   the one-file phone build carries the directions with it). Both builds call write() first, so the file follows the score.
   Usage: node tools/odyssey-directions.js   (or require('./odyssey-directions').write()) */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
function table() {
  const sc = JSON.parse(fs.readFileSync(path.join(root, 'odyssey/cineosis/score.json'), 'utf8'));
  const out = {};
  for (const s of sc.scenes) { if (!s.direction) continue;
    out[s.id] = { d: s.direction, p: s.primary && s.primary.symbol, pn: s.primary && s.primary.name, s: (s.secondary || []).map(x => x.symbol) }; }
  return out;
}
function write() {
  const t = table(), file = path.join(root, 'play/odyssey-game/directions.js');
  const js = `/* play/odyssey-game/directions.js — GENERATED by tools/odyssey-directions.js from odyssey/cineosis/score.json; do not edit.
   The sign score's direction block for each of the ${Object.keys(t).length} scenes of the cut, read by cinema.js C.plan (see odyssey/cineosis/WIRING.md). */
(function () { const OG = window.OG = window.OG || {}; OG.DIR = ${JSON.stringify(t)}; })();
`;
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== js) fs.writeFileSync(file, js);
  return { file, scenes: Object.keys(t).length };
}
module.exports = { table, write };
if (require.main === module) { const r = write(); console.log(path.relative(root, r.file) + ':', r.scenes, 'scenes'); }
